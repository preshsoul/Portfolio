export const getWritingBySlug = (slug) =>
  WRITINGS.find((item) => item.slug === slug || item.legacySlugs?.includes(slug));

export const getWritingTags = () =>
  Array.from(new Set(WRITINGS.flatMap((item) => item.tags || []))).sort((a, b) => a.localeCompare(b));

export const getRelatedWritings = (item, limit = 3) => {
  if (!item) return [];
  const tagSet = new Set(item.tags || []);

  return WRITINGS.filter((candidate) => candidate.slug !== item.slug)
    .map((candidate) => ({
      item: candidate,
      score: (candidate.tags || []).filter((tag) => tagSet.has(tag)).length,
    }))
    .filter(({ score }) => score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(({ item: candidate }) => candidate);
};
